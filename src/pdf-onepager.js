// Zero-dependency PDF one-pager generator (hand-rolled PDF 1.4).
// Produces a clean A4 brief: title bar, account/tier, angle, discovery Qs, sources.
// Returns a binary-safe (latin1) PDF string -> in n8n: Buffer.from(pdf,'latin1').toString('base64').
//<<PDFFN
function makeBriefPdf(d) {
  const W = 595, H = 842, ML = 45, MR = 45, usable = W - ML - MR;
  // transliterate to ASCII (Helvetica-safe; avoids garbled diacritics in a demo). ASCII-only source.
  const ascii = (s) => String(s == null ? '' : s).normalize('NFKD').split('').map(function (ch) { var c = ch.charCodeAt(0); if (c >= 768 && c <= 879) return ''; if (c === 8216 || c === 8217) return "'"; if (c === 8220 || c === 8221) return '"'; if ((c >= 8208 && c <= 8213) || c === 8722) return '-'; if (c === 8364) return 'EUR'; if (c < 32 || c > 126) return ''; return ch; }).join('')
  const esc = (s) => ascii(s).replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
  const wrap = (s, max) => { const w = ascii(s).split(/\s+/); const out = []; let cur = '';
    for (const t of w) { if ((cur + ' ' + t).trim().length > max) { if (cur) out.push(cur); cur = t; } else cur = (cur + ' ' + t).trim(); }
    if (cur) out.push(cur); return out.length ? out : ['']; };

  let s = '';                                  // content stream
  const rect = (x, y, w, h, r, g, b) => { s += `q ${r} ${g} ${b} rg ${x} ${y} ${w} ${h} re f Q\n`; };
  const text = (x, y, size, bold, str, rgb) => { const c = rgb || [0, 0, 0];
    s += `BT /F${bold ? 2 : 1} ${size} Tf ${c[0]} ${c[1]} ${c[2]} rg 1 0 0 1 ${x} ${y} Tm (${esc(str)}) Tj ET\n`; };
  let y = H - 64;
  const para = (str, size, bold, max, lead, rgb) => { for (const ln of wrap(str, max)) { text(ML, y, size, bold, ln, rgb); y -= lead; } };

  // header bar
  rect(0, H - 52, W, 52, 0.11, 0.14, 0.19);
  text(ML, H - 34, 17, true, 'DUVO   -   Pre-meeting brief', [1, 1, 1]);
  text(W - MR - 150, H - 33, 9, false, ascii(d.dateLabel || ''), [0.75, 0.8, 0.85]);
  y = H - 78;
  // account line
  text(ML, y, 14, true, `${d.company || ''}`); y -= 18;
  text(ML, y, 10.5, false, `${d.contactName || ''} - ${d.contactTitle || ''}`, [0.25, 0.25, 0.25]); y -= 22;
  // signal chip row
  const tierTxt = `ACCOUNT SIGNAL:  ${String(d.tier || '').toUpperCase()}`;
  text(ML, y, 11, true, tierTxt, d.tier === 'hot' ? [0.0, 0.5, 0.2] : d.tier === 'warm' ? [0.7, 0.5, 0] : [0.4, 0.4, 0.4]); y -= 15;
  para(`Stack (Sumble): ${d.stack || 'n/a'}`, 9.5, false, 100, 13, [0.3, 0.3, 0.3]); y -= 8;
  // divider
  rect(ML, y, usable, 0.8, 0.8, 0.8, 0.8); y -= 20;
  // angle
  text(ML, y, 11, true, 'THE ANGLE'); y -= 16;
  para(d.angle || '', 10.5, false, 95, 14.5); y -= 12;
  // discovery questions
  text(ML, y, 11, true, 'DISCOVERY QUESTIONS'); y -= 16;
  (d.questions || []).forEach((q, i) => { const ls = wrap(`${i + 1}.  ${q}`, 92);
    ls.forEach((ln, j) => { text(ML + (j ? 14 : 0), y, 10.5, false, ln); y -= 14; }); y -= 2; });
  y -= 8;
  // sources
  text(ML, y, 11, true, 'SOURCES'); y -= 16;
  (d.sources || []).forEach((src) => { para(`-  ${src.title || src.url}  (${src.url})`, 9, false, 110, 12.5, [0.2, 0.35, 0.6]); });
  // footer
  rect(ML, 46, usable, 0.8, 0.85, 0.85, 0.85);
  text(ML, 33, 8.5, false, `Evidence quality: ${d.evidence || 'n/a'}    -    Generated by Reply Intelligence    -    Human-in-the-loop: drafts never auto-send`, [0.5, 0.5, 0.5]);

  // assemble PDF objects with a correct xref
  const objs = [];
  objs[1] = '<< /Type /Catalog /Pages 2 0 R >>';
  objs[2] = '<< /Type /Pages /Kids [3 0 R] /Count 1 >>';
  objs[3] = `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${W} ${H}] /Contents 4 0 R /Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> >>`;
  objs[4] = `<< /Length ${Buffer.byteLength(s, 'latin1')} >>\nstream\n${s}endstream`;
  objs[5] = '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>';
  objs[6] = '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>';
  let pdf = '%PDF-1.4\n'; const off = [];
  for (let i = 1; i <= 6; i++) { off[i] = Buffer.byteLength(pdf, 'latin1'); pdf += `${i} 0 obj\n${objs[i]}\nendobj\n`; }
  const xrefAt = Buffer.byteLength(pdf, 'latin1');
  pdf += `xref\n0 7\n0000000000 65535 f \n`;
  for (let i = 1; i <= 6; i++) pdf += `${String(off[i]).padStart(10, '0')} 00000 n \n`;
  pdf += `trailer\n<< /Size 7 /Root 1 0 R >>\nstartxref\n${xrefAt}\n%%EOF`;
  return pdf;
}
