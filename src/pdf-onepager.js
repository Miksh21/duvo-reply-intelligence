// --- sample brief (real Ahold/Sumble shape) ---
const sample = {
  company: 'Ahold Delhaize', contactName: 'Petra Novak', contactTitle: 'VP Operations',
  dateLabel: 'Meeting: Tue, Jun 2', tier: 'hot',
  stack: 'UiPath, Blue Prism, Pega, Automation Anywhere, Celonis, SAP, ServiceNow - 1,090 automation roles open',
  angle: 'Ahold is mid-rollout of its EUR 5B "Save for Our Customers" program through 2028, leaning hard on shared sourcing across 15,000 suppliers. They run four overlapping RPA platforms with no orchestration layer - classic post-RPA sprawl. The opening is operational: bots break, no one owns the end-to-end process, and the savings program needs reliability they do not have today.',
  questions: [
    'You are running UiPath, Blue Prism and Pega in parallel - how are you handling orchestration and ownership across them today?',
    'Where in the "Save for Our Customers" program are automation failures actually costing you - sourcing, supply, or store ops?',
    'When a bot breaks mid-process, who owns the recovery, and how long is the typical mean-time-to-repair?',
    'You are hiring 1,000+ automation roles - is that capacity to build new bots, or to keep the existing estate alive?',
    'What would have to be true for you to consolidate onto one orchestration layer in the next two quarters?'
  ],
  sources: [
    { title: 'Ahold Delhaize Q4 2025 - Save for Our Customers EUR 5B', url: 'https://aholddelhaize.com/investors' },
    { title: 'Joint sourcing across 15,000 suppliers - press', url: 'https://aholddelhaize.com/news' },
    { title: 'Frans Muller on AI in procurement - interview', url: 'https://example.com/muller' }
  ],
  evidence: 'strong'
};
const fs = require('fs');
const pdf = makeBriefPdf(sample);
fs.writeFileSync('/tmp/brief-onepager.pdf', Buffer.from(pdf, 'latin1'));
